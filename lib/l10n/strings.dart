/// App texts in English and German.  Usage: `S.of(context).t('key')`.
class S {
  S(this.lang);
  final String lang;

  static const supported = ['en', 'de'];

  static S of(BuildContext context) =>
      Localizations.of<S>(context, S) ?? S('en');

  String t(String key, [Map<String, String>? args]) {
    var s = _strings[lang]?[key] ?? _strings['en']![key] ?? key;
    args?.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  String sessionType(SessionType type) => switch (type) {
        SessionType.training => t('training'),
        SessionType.race => t('race'),
        SessionType.event => t('event'),
      };

  String joinResult(JoinResult r) => switch (r) {
        JoinResult.joined => t('joined'),
        JoinResult.alreadyMember => t('alreadyMember'),
        JoinResult.notFound => t('codeNotFound'),
        JoinResult.full => t('teamFull'),
      };
}

class SDelegate extends LocalizationsDelegate<S> {
  const SDelegate();
  @override
  bool isSupported(Locale locale) => S.supported.contains(locale.languageCode);
  @override
  Future<S> load(Locale locale) => SynchronousFuture(S(locale.languageCode));
  @override
  bool shouldReload(SDelegate old) => false;
}

